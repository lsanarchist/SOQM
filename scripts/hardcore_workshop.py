#!/usr/bin/env python3
"""Render the reviewed hardcore-workshop policy as late KubeJS recipes.

The policy contains exact pinned native recipe IDs and serializer-preserving
payloads. No mod archives are fetched or executed by this authoring command.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
POLICY = ROOT / "metadata/hardcore_workshop.json"
SCRIPT = ROOT / "overrides/kubejs/server_scripts/qm_expert_hardcore_workshop.js"


def load_policy() -> dict:
    policy = json.loads(POLICY.read_text(encoding="utf-8"))
    ids = [row["id"] for row in policy["recipes"]]
    if len(set(ids)) != len(ids):
        raise ValueError("Hardcore workshop recipe IDs must be unique")
    if policy["script_priority"] >= 0:
        raise ValueError("Workshop overrides must load after the priority-zero baseline")
    if policy["food_recipe_changes"]:
        raise ValueError("Food changes are outside this policy")
    removed = set(policy["remove_ids"])
    queued = set(policy["remove_added_ids"])
    if queued != {ident for ident in removed if ident.startswith("kubejs:")}:
        raise ValueError("Every superseded authored recipe needs explicit queued-addition removal")
    if removed & set(ids):
        raise ValueError("Replacement IDs must not overlap the removed native/baseline IDs")
    for row in policy["recipes"]:
        if not set(row["replaces"]) <= removed:
            raise ValueError("An overridden source recipe was not removed: " + row["id"])
        native = row.get("native_evidence")
        if native and row["recipe"]["type"] != native["serializer"]:
            raise ValueError("Native serializer changed: " + row["id"])
    return policy


def render(policy: dict) -> str:
    rows = [{"id": row["id"], "recipe": row["recipe"]} for row in policy["recipes"]]
    return (
        f"// priority: {policy['script_priority']}\n"
        "// Generated by scripts/hardcore_workshop.py from metadata/hardcore_workshop.json.\n"
        "// Explicit late replacements retain native storage/tank serializers and prior-tier bootstrap.\n"
        "ServerEvents.recipes(function(event) {\n"
        "  var removeIds = " + json.dumps(policy["remove_ids"], ensure_ascii=False) + ";\n"
        "  removeIds.forEach(function(id) { event.remove({id:id}); });\n"
        "  // KubeJS 2101.7.2: event.remove filters native originals only, not queued custom additions.\n"
        "  var removeAddedIds = " + json.dumps(policy["remove_added_ids"], ensure_ascii=False) + ";\n"
        "  event.addedRecipes.forEach(function(recipe) {\n"
        "    if (removeAddedIds.indexOf(String(recipe.getId())) !== -1) recipe.remove();\n"
        "  });\n"
        "  var recipes = " + json.dumps(rows, ensure_ascii=False, indent=2) + ";\n"
        "  recipes.forEach(function(row) { event.custom(row.recipe).id(row.id); });\n"
        "});\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the generated recipe script is stale")
    args = parser.parse_args()
    policy = load_policy()
    expected = render(policy)
    if args.check:
        if not SCRIPT.is_file() or SCRIPT.read_text(encoding="utf-8") != expected:
            raise SystemExit("Hardcore workshop script is stale; run python3 scripts/hardcore_workshop.py")
    else:
        SCRIPT.write_text(expected, encoding="utf-8")
    print(f"Hardcore workshop: {len(policy['recipes'])} recipes, {len(policy['remove_ids'])} exact source removals")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
